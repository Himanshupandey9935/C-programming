
           // THIS CODE EXPLAINS HOW THE COMPUTER DISPLAYS OUTPUT TO THE USER

#include <stdio.h>

int main() {

// For INTEGER output -
int age = 22;
printf("Age = %d\n", age);

// For CHARACTER output -
char star = '*';
printf("Star = %c\n", star);

// For FLOAT output -
float number = 2.2;
printf("Number = %f\n", number);

// For STRING output -
char name[] = "Himanshu";
printf("Name = %s\n", name);

return 0;

}