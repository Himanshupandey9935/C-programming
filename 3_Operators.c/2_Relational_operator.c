// relational operators 

#include <stdio.h>

int main() {

    int a = 4;
    int b = 4;

    printf("%d \n", a == b);// Equal too operator = this is used for checking A is equal to B 

    printf("%d \n", a >= b);// Greater than or Greater equal to = this is for checking A>B or A>=B

    printf("%d \n", a <= b);// Less than or Less than equal to  = <,<= this is for checking A<B or A<=B

    printf("%d \n", a != b);// Not equal to = it is opposite of equal to 


    return 0;
}
